-- Combined normalized table for all project data
CREATE TABLE project_data (
    id SERIAL PRIMARY KEY,
    excel_file TEXT NOT NULL,
    excel_sheet TEXT NOT NULL,
    project_name TEXT NOT NULL,
    plant_name TEXT,
    company_name TEXT,
    owner_partner TEXT,
    stakeholders TEXT,
    contact_name TEXT,
    contact_email TEXT,
    country TEXT,
    zip TEXT,
    city TEXT,
    street TEXT,
    website TEXT,
    project_status TEXT NOT NULL,
    status_date TIMESTAMP,
    project_stage JSONB,
    project_type TEXT,
    primary_product TEXT,
    secondary_product TEXT,
    product TEXT,
    technology TEXT,
    technology_fate_of_carbon TEXT,
    end_use TEXT,
    capacity_value DOUBLE PRECISION,
    capacity_unit TEXT,
    capacity_description TEXT,
    length_km DOUBLE PRECISION,
    operating_pressure_bar DOUBLE PRECISION,
    repurposed_new TEXT,
    port_code TEXT,
    investment_capex DOUBLE PRECISION,
    investment_capex_currency TEXT,
    github_mapper_link TEXT,
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
